def test_display():
    assert check_display(make_host(env={"DISPLAY": ":0"})).status is CheckStatus.OK
    wayland = check_display(make_host(env={"WAYLAND_DISPLAY": "wayland-0"}))
    assert wayland.status is CheckStatus.WARNING
    assert "XWayland" in wayland.hint
    none = check_display(make_host(env={"DISPLAY": ""}))
    assert none.status is CheckStatus.ERROR
    assert none.blocking


@pytest.mark.parametrize(
    ("display", "socket"),
    [(":0", "X0"), (":1.0", "X1"), ("unix:2", "X2"), ("localhost:10.0", None), ("x", None)],
)
def test_x11_socket(tmp_path, display, socket):
    host = make_host(env={"DISPLAY": display}, x11_dir=tmp_path)
    assert host.x11_socket() == (tmp_path / socket if socket else None)


# /proc/net/unix real de WSL con WSLg (:0, con fichero) y Xvfb :96 (solo abstracto).
PROC_NET_UNIX = """\
Num       RefCount Protocol Flags    Type St Inode Path
ffff8b4b106ee780: 00000002 00000000 00010000 0001 01  2529 /tmp/.X11-unix/X0
ffff8b4b23502880: 00000002 00000000 00010000 0001 01  9663 @/tmp/.X11-unix/X96
ffff8b4b23502881: 00000002 00000000 00010000 0001 01  9664
"""


def test_x_server_on_an_abstract_socket(tmp_path):
    sockets = tmp_path / "x11"
    sockets.mkdir()
    unix = tmp_path / "unix"
    unix.write_text(PROC_NET_UNIX.replace(X11_SOCKET_DIR.as_posix(), sockets.as_posix()))

    def listening(display):
        host = make_host(env={"DISPLAY": display}, x11_dir=sockets, unix=unix)
        return host.x11_server_listening()

    assert listening(":96") is True
    assert listening(":0") is True  # también aparece con ruta
    assert listening(":9") is False
    assert listening(":1") is False
    assert listening("localhost:10.0") is None
    no_table = make_host(env={"DISPLAY": ":9"}, x11_dir=sockets, unix=tmp_path / "no")
    assert no_table.x11_server_listening() is None
    assert check_display(no_table).status is CheckStatus.OK


def test_display_without_x_server(tmp_path):
    unix = tmp_path / "unix"
    unix.write_text(PROC_NET_UNIX)
    host = make_host(env={"DISPLAY": ":0"}, x11_dir=tmp_path, unix=unix)

    check = check_display(host)
    assert check.status is CheckStatus.WARNING
    assert "no hay ningún servidor X" in check.detail
    assert not check.blocking

    (tmp_path / "X0").touch()
    assert check_display(host).status is CheckStatus.OK
    # Pantalla remota (ssh -X): no se puede comprobar, se da por buena.
    remote = make_host(env={"DISPLAY": "localhost:10.0"}, x11_dir=tmp_path, unix=unix)
    assert check_display(remote).status is CheckStatus.OK


def test_opengl_ok_with_vendor():
    check = check_opengl(make_host(parse_ldconfig(LDCONFIG_FULL)), 32)

    assert check.status is CheckStatus.OK
    assert check.detail == "libGL.so.1 (mesa)"
    assert check.label == "OpenGL de 32 bits"


def test_opengl_32_missing_is_an_error_with_hint():
    """Regresión del sprint 4: sin GL de 32 bits, mkxp-z no puede crear la ventana."""
    check = check_opengl(make_host(parse_ldconfig(LDCONFIG_NO_GL32)), 32)

    assert check.status is CheckStatus.ERROR
    assert check.hint == OPENGL_HINTS[32]
    assert "libgl1:i386" in check.hint
    # El de 64 bits sí está.
    assert check_opengl(make_host(parse_ldconfig(LDCONFIG_NO_GL32)), 64).status is CheckStatus.OK


def test_opengl_glvnd_without_vendor_is_an_error():
    libs = {"libGL.so.1": {32}, "libGLX.so.0": {32}, "libGLX_indirect.so.0": {32}}
    check = check_opengl(make_host(libs), 32)

    assert check.status is CheckStatus.ERROR
    assert "sin driver" in check.detail


def test_opengl_without_glvnd_and_unknown():
    assert check_opengl(make_host({"libGL.so.1": {32}}), 32).status is CheckStatus.OK
    unknown = check_opengl(make_host(None), 32)
    assert unknown.status is CheckStatus.UNKNOWN
    assert not unknown.blocking


def test_check_requirements_for_mkxp_z_game(make_game, tmp_path):
    game = make_game(exe="mkxp-z")
    mounts = tmp_path / "mounts"
    mounts.write_text(f"C:\\134 {game.resolve().as_posix()} 9p rw 0 0\n")
    host = make_host(parse_ldconfig(LDCONFIG_NO_GL32), {"DISPLAY": ":0"}, mounts)

    checks = {c.id: c for c in check_requirements(analyze_game(game), host)}

    assert list(checks) == ["display", "opengl", "filesystem"]
    assert checks["opengl"].status is CheckStatus.ERROR
    assert checks["filesystem"].status is CheckStatus.WARNING
    assert "WSL" in checks["filesystem"].detail
    assert checks["filesystem"].to_dict()["status"] == "warning"


def test_games_without_opengl_skip_that_check(make_game):
    host = make_host({}, {"DISPLAY": ":0"})

    checks = check_requirements(analyze_game(make_game(exe="rgss")), host)

    assert [c.id for c in checks] == ["display", "filesystem"]
    assert checks[1].status is CheckStatus.UNKNOWN
