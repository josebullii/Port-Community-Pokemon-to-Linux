# Ubuntu 24.04 con wine32:i386 instalado con --no-install-recommends: sin GL de 32 bits.
LDCONFIG_NO_GL32 = "\n".join(
    line for line in LDCONFIG_FULL.splitlines() if "libGL" not in line or "x86-64" in line
)

MOUNTS = """\
/dev/sdd / ext4 rw,relatime 0 0
C:\\134 /mnt/c 9p rw,noatime,aname=drvfs 0 0
tmpfs /mnt/c/temp tmpfs rw 0 0
servidor:/juegos /mnt/mis\\040juegos nfs4 rw 0 0
"""


def make_host(
    libraries=None, env=None, mounts_file=Path("/no/existe"), x11_dir=None, unix=Path("/no")
):
    host = HostSystem(
        env=env or {}, mounts_file=mounts_file, x11_socket_dir=x11_dir, unix_sockets_file=unix
    )
    host.__dict__["shared_libraries"] = libraries  # sustituye a ldconfig -p
    return host


# --- ldconfig y montajes -----------------------------------------------------------


def test_parse_ldconfig():
    libs = parse_ldconfig(LDCONFIG_FULL)

    assert libs["libGL.so.1"] == {32, 64}
    assert libs["libGLX_mesa.so.0"] == {32, 64}
    assert libs["libfoo.so.1"] == {64}
    assert libs["libbar.so.1"] == {32}
    assert "libarm.so.1" not in libs
    assert "libaarch.so.1" not in libs
    assert "liblibc5.so.1" not in libs


def test_parse_mounts_and_find_filesystem():
    mounts = parse_mounts(MOUNTS)

    assert ("/mnt/mis juegos", "nfs4") in mounts
    assert filesystem_of(PurePosixPath("/root/games/Pokemon Z"), mounts) == "ext4"
    assert filesystem_of(PurePosixPath("/mnt/c/Users/yo/Pokemon Z"), mounts) == "9p"
    assert filesystem_of(PurePosixPath("/mnt/c"), mounts) == "9p"
    assert filesystem_of(PurePosixPath("/mnt/c/temp/x"), mounts) == "tmpfs"
    assert filesystem_of(PurePosixPath("/mnt/cosas"), mounts) == "ext4"  # no es /mnt/c
    assert filesystem_of(PurePosixPath("/mnt/mis juegos/Z"), mounts) == "nfs4"
    assert filesystem_of(PurePosixPath("/x"), []) is None


def test_host_reads_mounts_file(tmp_path):
    mounts = tmp_path / "mounts"
    shared = tmp_path.resolve().as_posix()
    mounts.write_text(f"/dev/sda1 / ext4 rw 0 0\nC:\\134 {shared} 9p rw 0 0\n")
    host = HostSystem(env={}, mounts_file=mounts)

    assert host.filesystem_type(tmp_path) == "9p"
    assert HostSystem(env={}, mounts_file=tmp_path / "no").filesystem_type(tmp_path) is None


def test_host_runs_ldconfig(monkeypatch):
    calls = []

    def fake_run(args, **kwargs):
        calls.append(args)
        return subprocess.CompletedProcess(args, 0, LDCONFIG_FULL, "")

    monkeypatch.setattr(host_module.subprocess, "run", fake_run)
    host = HostSystem(env={}, which=lambda name: "/usr/sbin/ldconfig")

    assert host.has_library("libGL.so.1", 32) is True
    assert host.has_library("libvulkan.so.1", 32) is False
    assert host.libraries_matching("libGLX_", ".so.0", 32) == ["libGLX_mesa.so.0"]
    assert calls == [["/usr/sbin/ldconfig", "-p"]]  # una sola vez: se guarda


@pytest.mark.parametrize(
    "result",
    [
        subprocess.CompletedProcess([], 1, "", "error"),
        subprocess.TimeoutExpired("ldconfig", 15),
        OSError("permiso denegado"),
    ],
)
def test_ldconfig_failures_mean_unknown(monkeypatch, result):
    def fake_run(args, **kwargs):
        if isinstance(result, BaseException):
            raise result
        return result

    monkeypatch.setattr(host_module.subprocess, "run", fake_run)
    host = HostSystem(env={}, which=lambda name: "/usr/sbin/ldconfig")

    assert host.shared_libraries is None
    assert host.has_library("libGL.so.1", 32) is None
    assert host.libraries_matching("libGLX_", ".so.0", 32) is None


def test_without_ldconfig_libraries_are_unknown(tmp_path):
    host = HostSystem(env={}, which=lambda name: None, ldconfig_locations=(str(tmp_path / "x"),))
    assert host.shared_libraries is None


def test_ldconfig_found_outside_path(tmp_path, monkeypatch):
    """En Debian, /usr/sbin no está en el PATH de los usuarios normales."""
    ldconfig = tmp_path / "ldconfig"
    ldconfig.write_text("")
    seen = []
    monkeypatch.setattr(
        host_module.subprocess,
        "run",
        lambda args, **kw: seen.append(args) or subprocess.CompletedProcess(args, 0, "", ""),
    )
    host = HostSystem(env={}, which=lambda name: None, ldconfig_locations=(str(ldconfig),))

    assert host.shared_libraries == {}
    assert seen == [[str(ldconfig), "-p"]]


